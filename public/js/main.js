  function renderWeek() {
    const DAYS = { SU: 0, MO: 1, TU: 2, WE: 3, TH: 4, FR: 5, SA: 6 };
    const mins = (hm) => {
      const [x, y] = hm.split(":").map(Number);
      return x * 60 + y;
    };
    // Only meetings with a fixed day and time take part (departmental meetings are skipped).
    const meets = D.serviceSchedule
      .filter((s) => s.calendar)
      .map((s) => ({
        s,
        day: DAYS[s.calendar.weekday],
        start: mins(s.calendar.start),
        end: mins(s.calendar.end),
      }));

    // Ghana time is UTC, so UTC fields are used throughout.
    function upcoming() {
      const now = Date.now();
      const base = new Date(now);
      let best = null;
      meets.forEach((m) => {
        for (let wk = 0; wk < 2; wk++) {
          const add = ((m.day - base.getUTCDay() + 7) % 7) + wk * 7;
          const t0 =
            Date.UTC(base.getUTCFullYear(), base.getUTCMonth(), base.getUTCDate() + add) + m.start * 6e4;
          const t1 = t0 + (m.end - m.start) * 6e4;
          if (t1 > now && (!best || t0 < best.t0)) best = { s: m.s, t0, t1 };
        }
      });
      return best;
    }

    const els = { d: $("#cdD"), h: $("#cdH"), m: $("#cdM"), s: $("#cdS") };
    let cur = null;
    function show(n) {
      cur = n;
      const dt = new Date(n.t0);
      $("#nextTitle").textContent = n.s.title;
      $("#nextWhen").textContent =
        `${WEEKDAYS[dt.getUTCDay()]} ${dt.getUTCDate()} ${MONTHS[dt.getUTCMonth()]}, ${n.s.time} at ${n.s.venue}`;
      const map = $("#nextMap");
      if (n.s.map) {
        map.href = n.s.map;
        map.hidden = false;
      } else map.hidden = true;
    }
    function tick() {
      if (!cur || cur.t1 <= Date.now()) {
        const n = upcoming();
        if (!n) return;
        show(n);
      }
      let diff = cur.t0 - Date.now();
      if (diff <= 0) {
        $("#countdown").hidden = true;
        $("#nextWhen").textContent = `Happening now at ${cur.s.venue}. Come and join us.`;
        return;
      }
      $("#countdown").hidden = false;
      const days = Math.floor(diff / 864e5);
      diff -= days * 864e5;
      const hrs = Math.floor(diff / 36e5);
      diff -= hrs * 36e5;
      const mm = Math.floor(diff / 6e4);
      diff -= mm * 6e4;
      const secs = Math.floor(diff / 1e3);
      els.d.textContent = days;
      els.h.textContent = String(hrs).padStart(2, "0");
      els.m.textContent = String(mm).padStart(2, "0");
      els.s.textContent = String(secs).padStart(2, "0");
    }
    tick();
    setInterval(tick, 1000);

    const w = D.weeklyWord;
    $("#weekVerse").textContent = `“${w.verse}”`;
    $("#weekRef").textContent = w.reference;
  }

