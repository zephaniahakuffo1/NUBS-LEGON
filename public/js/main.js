/* Runs a scroll handler at most once per frame, so scrolling stays smooth. */
function raf(fn) {
  let t = false;
  return function () {
    if (t) return;
    t = true;
    requestAnimationFrame(() => {
      t = false;
      fn();
    });
  };
}

