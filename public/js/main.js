  function renderQuiz() {
    const body = $("#quizBody");
    const questions = D.quiz;
    const byId = (id) => D.auxiliaries.find((a) => a.id === id);
    let step = 0;
    let scores = {};
    let home = null; // "byl" or "bmw", chosen in the first question

    function showQuestion() {
      const q = questions[step];
      body.replaceChildren(
        h("p", { class: "quiz-step", text: `Question ${step + 1} of ${questions.length}` }),
        h("p", { class: "quiz-q", text: q.question }),
        h(
          "div",
          { class: "quiz-answers" },
          q.answers.map((a) => h("button", { type: "button", onclick: () => choose(a) }, a.text))
        )
      );
    }

    function choose(answer) {
      if (answer.home) home = answer.home;
      for (const [id, pts] of Object.entries(answer.points || {})) scores[id] = (scores[id] || 0) + pts;
      step++;
      if (step < questions.length) showQuestion();
      else showResult();
    }

    // Service auxiliaries are every auxiliary except BYL and BMW (those are by default for ladies and men).
    function ranked() {
      const pool = D.auxiliaries.filter((a) => a.id !== "byl" && a.id !== "bmw");
      // random tie-break so no auxiliary is favoured by its position in the list
      return pool
        .map((a) => ({ a, s: scores[a.id] || 0, r: Math.random() }))
        .sort((x, y) => y.s - x.s || x.r - y.r);
    }

    function showResult() {
      const [first, second] = ranked();
      const best = first.a;
      const close = second && second.s > 0 && second.s >= first.s - 1; // runner-up is genuinely close
      const homeAux = home ? byId(home) : null;
      body.replaceChildren(
        h(
          "div",
          { class: "quiz-result" },
          homeAux
            ? h(
                "p",
                { class: "quiz-home" },
                h("b", { text: "Your home: " }),
                `${homeAux.name} (${homeAux.short}). Every ${home === "byl" ? "young lady" : "young man"} is part of it automatically.`
              )
            : null,
          h("p", { class: "quiz-step", text: "Where your gifts fit best" }),
          h("h4", { text: best.name }),
          h("p", { class: "aux-tag", text: best.tagline }),
          h("p", {
            text:
              best.description.length > 260
                ? best.description.slice(0, 257).trim() + "..."
                : best.description,
          }),
          close
            ? h("p", { class: "quiz-also" }, h("b", { text: "Also a strong fit: " }), second.a.name)
            : null,
          h(
            "div",
            { class: "row-actions" },
            h(
              "button",
              { class: "btn btn-primary btn-sm", type: "button", onclick: () => openJoin(best.id) },
              "Join this auxiliary"
            ),
            h(
              "button",
              { class: "btn btn-outline btn-sm", type: "button", onclick: () => highlight(best.id) },
              "See its card"
            ),
            h(
              "button",
              { class: "btn btn-outline btn-sm", type: "button", onclick: restart },
              "Retake the quiz"
            )
          )
        )
      );
    }

    function highlight(id) {
      $$(".aux-card").forEach((c) => c.classList.remove("is-match"));
      const card = $(`#aux-${id}`);
      if (!card) return;
      card.classList.add("is-match");
      card.scrollIntoView({ behavior: "smooth", block: "center" });
    }

    function restart() {
      step = 0;
      scores = {};
      home = null;
      $$(".aux-card").forEach((c) => c.classList.remove("is-match"));
      showQuestion();
    }

    showQuestion();
  }

